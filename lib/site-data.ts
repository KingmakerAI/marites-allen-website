export function localOf(dt: Date, h: number, mi: number) {
  const utc = Date.UTC(dt.getFullYear(), dt.getMonth(), dt.getDate(), h - 8, mi);
  return new Date(utc).toLocaleTimeString([], { hour: "numeric", minute: "2-digit" });
}
