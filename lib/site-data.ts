export function makeWeekdayDates(count = 8) {
  const wd = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
  const mo = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const out: { key: string; wd: string; d: number; mo: string; dt: Date }[] = [];
  const d = new Date();
  let added = 0;
  let cursor = 1;
  while (added < count) {
    const dt = new Date(d.getFullYear(), d.getMonth(), d.getDate() + cursor);
    if (dt.getDay() !== 0) {
      out.push({
        key: dt.toISOString().slice(0, 10),
        wd: wd[dt.getDay()],
        d: dt.getDate(),
        mo: mo[dt.getMonth()],
        dt
      });
      added++;
    }
    cursor++;
  }
  return out;
}

